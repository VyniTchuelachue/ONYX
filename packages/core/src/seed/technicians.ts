const minutesAgo = (now: Date, m: number) => new Date(now.getTime() - m * 60_000).toISOString();

export function seedToTechnician(s: SeedTechnician, now: Date = new Date()): TechnicianPrivate {
  const phone = seedPhone(s.n);
  return {
    id: seedTechnicianId(s.n),
    userId: null,
    businessName: s.businessName,
    ownerName: s.ownerName,
    bio: s.bio,
    phone,
    whatsapp: phone,
    specialties: s.specialties,
    vehicleTypes: s.vehicleTypes,
    location: { lat: s.lat, lng: s.lng },
    address: null,
    area: s.area,
    city: s.city,
    corridors: s.corridors,
    serviceRadiusKm: s.serviceRadiusKm,
    mobileService: s.mobileService,
    hasTowTruck: s.hasTowTruck,
    openingHours: s.openingHours,
    yearsExperience: s.yearsExperience,
    photoUrl: null,
    verificationStatus: s.verificationStatus,
    verificationNote: s.verificationNote ?? null,
    verifiedAt: s.verificationStatus === 'verified' ? minutesAgo(now, (s.joinedDaysAgo - 1) * 1440) : null,
    availability: s.availability,
    availabilityUpdatedAt: minutesAgo(now, s.lastSeenMinutesAgo + 30),
    lastSeenAt: minutesAgo(now, s.lastSeenMinutesAgo),
    ratingAvg: s.ratingAvg,
    ratingCount: s.ratingCount,
    jobsCompleted: s.jobsCompleted,
    avgResponseMinutes: s.avgResponseMinutes,
    createdAt: minutesAgo(now, s.joinedDaysAgo * 1440),
  };
}
