/**
 * Writes supabase/seed.sql from the seed data in packages/core (single source of truth
 * for the demo backend and the development database).
 *
 *   npm run db:seed
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { SEED_TECHNICIANS, seedPhone, seedTechnicianId } from '@onyx/core/seed';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../supabase/seed.sql');

const q = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (xs: string[]) => (xs.length ? `array[${xs.map(q).join(', ')}]::text[]` : `'{}'::text[]`);

const rows = SEED_TECHNICIANS.map((s) => {
  const phone = seedPhone(s.n);
  const values = [
    q(seedTechnicianId(s.n)),
    q(s.businessName),
    q(s.ownerName),
    q(s.bio),
    q(phone),
    q(phone),
    arr(s.specialties),
    arr(s.vehicleTypes),
    String(s.lat),
    String(s.lng),
    q(s.area),
    q(s.city),
    arr(s.corridors),
    String(s.serviceRadiusKm),
    String(s.mobileService),
    String(s.hasTowTruck),
    q(s.openingHours),
    String(s.yearsExperience),
    `'${s.verificationStatus}'`,
    q(s.verificationNote ?? null),
    s.verificationStatus === 'verified' ? `now() - interval '${s.joinedDaysAgo - 1} days'` : 'null',
    `'${s.availability}'`,
    `now() - interval '${s.lastSeenMinutesAgo + 30} minutes'`,
    `now() - interval '${s.lastSeenMinutesAgo} minutes'`,
    s.ratingAvg.toFixed(2),
    String(s.ratingCount),
    String(s.jobsCompleted),
    s.avgResponseMinutes === null ? 'null' : String(s.avgResponseMinutes),
    String(s.jobsCompleted),
    `now() - interval '${s.joinedDaysAgo} days'`,
  ];
  return `  (${values.join(', ')})`;
});

const sql = `-- GENERATED by scripts/generate-seed.ts from packages/core/src/seed — do not edit by hand.
--
-- FICTIONAL development data: invented businesses and people, phone numbers in the
-- unallocated +237 600 00 0x xx range. Never run this against production.
--
-- Listings are not linked to accounts (user_id is null). To manage one from the
-- technician app, link it to your account:
--   update public.technicians set user_id = '<your auth user id>'
--    where id = '${seedTechnicianId(1)}';

insert into public.technicians (
  id, business_name, owner_name, bio, phone, whatsapp, specialties, vehicle_types, lat, lng, area, city,
  corridors, service_radius_km, mobile_service, has_tow_truck, opening_hours, years_experience,
  verification_status, verification_note, verified_at, availability, availability_updated_at, last_seen_at,
  rating_avg, rating_count, jobs_completed, avg_response_minutes, accepted_count, created_at
) values
${rows.join(',\n')}
on conflict (id) do nothing;
`;

writeFileSync(out, sql, 'utf8');
console.log(`Wrote ${SEED_TECHNICIANS.length} technicians to ${path.relative(process.cwd(), out)}`);
